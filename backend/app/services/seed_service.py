"""
seed_service.py
-----------------
Runs once, automatically, on application startup (see app.main.on_startup)
if the job_postings table is empty. Pulls a balanced sample of postings
from the synthetic dataset generated by pipelines/generate_dataset.py and
runs each one through the *real* analyze_and_persist() pipeline — i.e.
every "demo" row on a freshly deployed instance is a genuine model
prediction with real SHAP explanations and real Trust Graph scores, not
hardcoded fixture data.

This exists purely so that opening a freshly deployed single-URL instance
shows a populated Trusted Jobs Feed and Analytics Dashboard immediately,
instead of an empty state on first visit.

Seeding runs with `run_company_intelligence=False` — bulk-seeding 40
postings should not trigger 40 real Gemini API calls (cost/latency) on
every fresh container boot. Gemini company intelligence still runs
normally for real user-submitted analyses.

v1.1.0: failures are now logged with a full traceback (not just the
exception message) so a systemic bug — e.g. the previously-shipped
'FraudPredictor' object has no attribute 'predict' issue, caused by a
method accidentally defined outside its class — is actually diagnosable
from container logs instead of looking like a generic "skipped one row".
If EVERY row in the batch fails, that's treated as a loud error, not a
quiet no-op, since that pattern means something is systemically broken
rather than one bad row of data.
"""
import os
import traceback
from pathlib import Path

import pandas as pd
from sqlalchemy.orm import Session

from app.models.models import JobPosting
from app.schemas.jobs import JobAnalyzeRequest
from app.services.analysis_service import analyze_and_persist

_env_root = os.environ.get("DATA_ROOT")
DATA_ROOT = (
    Path(_env_root) if _env_root
    else Path(__file__).resolve().parent.parent.parent.parent / "data"
)
SEED_CSV = DATA_ROOT / "raw" / "job_postings.csv"

SEED_COUNT = 40  # small enough to run in a few seconds on container boot


def seed_if_empty(db: Session, count: int = SEED_COUNT) -> None:
    already_has_data = db.query(JobPosting.id).first() is not None
    if already_has_data:
        return

    if not SEED_CSV.exists():
        print(f"[seed] {SEED_CSV} not found — skipping demo seeding (empty instance is still fully usable).")
        return

    df = pd.read_csv(SEED_CSV)
    # take a balanced mix so the dashboard shows a realistic fake/real split
    fake = df[df["fraudulent"] == 1].sample(n=min(count // 3, (df["fraudulent"] == 1).sum()), random_state=7)
    real = df[df["fraudulent"] == 0].sample(n=min(count - len(fake), (df["fraudulent"] == 0).sum()), random_state=7)
    sample = pd.concat([fake, real]).sample(frac=1, random_state=7)  # shuffle

    seeded = 0
    attempted = 0
    last_error = None
    for _, row in sample.iterrows():
        attempted += 1
        try:
            payload = JobAnalyzeRequest(
                title=str(row["title"]),
                raw_text=str(row["description"]),
                company_name=str(row["company_name"]) if pd.notna(row["company_name"]) else None,
                location=str(row["location"]) if pd.notna(row["location"]) else None,
                contact_email=str(row["contact_email"]) if pd.notna(row["contact_email"]) else None,
                salary_min=float(row["salary_min"]) if pd.notna(row["salary_min"]) else None,
                salary_max=float(row["salary_max"]) if pd.notna(row["salary_max"]) else None,
            )
            analyze_and_persist(db, payload, user=None, use_cache=False, run_company_intelligence=False)
            seeded += 1
        except Exception as exc:
            # one bad row shouldn't block the rest of the seed batch, but
            # the failure must be VISIBLE in logs, not just a one-line
            # exception message — that's what made the earlier
            # 'FraudPredictor' object has no attribute 'predict' bug hard
            # to diagnose from Docker logs alone.
            last_error = exc
            print(f"[seed] skipped one row due to: {exc}")
            print(traceback.format_exc())
            db.rollback()

    if seeded == 0 and attempted > 0:
        # every single row failed — this is a systemic bug (bad model
        # artifacts, a broken predict() call, a schema mismatch), not bad
        # data. Say so loudly rather than printing a misleadingly calm
        # "seeded 0 demo postings" line.
        print(
            f"[seed] ERROR: all {attempted} demo rows failed to seed — this indicates a "
            f"systemic problem (e.g. model artifacts, predictor wiring), not bad data. "
            f"Last error: {last_error}"
        )
    else:
        print(f"[seed] seeded {seeded}/{attempted} demo postings on first boot.")
